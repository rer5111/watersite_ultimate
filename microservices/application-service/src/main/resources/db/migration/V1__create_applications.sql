CREATE TABLE applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    applicant_username VARCHAR(120) NOT NULL,
    application_text VARCHAR(4000) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_applications PRIMARY KEY (id),
    CONSTRAINT ck_applications_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE INDEX ix_applications_applicant_username ON applications (applicant_username);
CREATE INDEX ix_applications_status ON applications (status);
CREATE INDEX ix_applications_created_at ON applications (created_at DESC, id DESC);
