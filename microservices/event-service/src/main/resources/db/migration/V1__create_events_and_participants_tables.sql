CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(64) NOT NULL,
    title VARCHAR(120) NOT NULL,
    description TEXT NOT NULL,
    short_description VARCHAR(500) NOT NULL DEFAULT '',
    image VARCHAR(255) NOT NULL DEFAULT '',
    season_number INTEGER NOT NULL,
    organizer VARCHAR(120) NOT NULL DEFAULT '',
    status VARCHAR(32) NOT NULL DEFAULT 'PLANNED',
    start_date DATE,
    end_date DATE,
    display_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_events PRIMARY KEY (id),
    CONSTRAINT uk_events_code UNIQUE (code),
    CONSTRAINT ck_events_display_order_nonnegative CHECK (display_order >= 0)
);

CREATE INDEX ix_events_season_number ON events (season_number);
CREATE INDEX ix_events_status ON events (status);
CREATE INDEX ix_events_organizer ON events (organizer);
CREATE INDEX ix_events_dates ON events (start_date, end_date);
CREATE INDEX ix_events_active_display_order ON events (active, display_order);

CREATE TABLE event_participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_id BIGINT NOT NULL,
    user_id BIGINT,
    username VARCHAR(64) NOT NULL,
    role VARCHAR(32) NOT NULL DEFAULT 'PARTICIPANT',
    notes VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_event_participants PRIMARY KEY (id),
    CONSTRAINT fk_event_participants_event FOREIGN KEY (event_id) REFERENCES events (id) ON DELETE CASCADE,
    CONSTRAINT uk_event_participant UNIQUE (event_id, username)
);

CREATE INDEX ix_event_participants_event_id ON event_participants (event_id);
CREATE INDEX ix_event_participants_username ON event_participants (username);

