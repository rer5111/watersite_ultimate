CREATE TABLE donation_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(64) NOT NULL,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(500),
    price_rub NUMERIC(12, 2) NOT NULL,
    display_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_donation_types PRIMARY KEY (id),
    CONSTRAINT uk_donation_types_code UNIQUE (code),
    CONSTRAINT ck_donation_types_price_positive CHECK (price_rub > 0),
    CONSTRAINT ck_donation_types_display_order_nonnegative CHECK (display_order >= 0)
);

CREATE TABLE donations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    player_id BIGINT NOT NULL,
    donation_type_id BIGINT NOT NULL,
    amount_rub NUMERIC(12, 2) NOT NULL,
    payment_reference VARCHAR(128),
    donated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_donations PRIMARY KEY (id),
    CONSTRAINT fk_donations_donation_type FOREIGN KEY (donation_type_id)
        REFERENCES donation_types (id) ON DELETE RESTRICT,
    CONSTRAINT uk_donations_payment_reference UNIQUE (payment_reference),
    CONSTRAINT ck_donations_amount_positive CHECK (amount_rub > 0)
);

CREATE INDEX ix_donations_player_id ON donations (player_id);
CREATE INDEX ix_donations_donation_type_id ON donations (donation_type_id);
CREATE INDEX ix_donations_donated_at ON donations (donated_at);

