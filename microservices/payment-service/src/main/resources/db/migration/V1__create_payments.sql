CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    payer_username VARCHAR(120) NOT NULL,
    payment_date DATE NOT NULL,
    amount_rub NUMERIC(12, 2) NOT NULL,
    external_reference VARCHAR(128),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_payments PRIMARY KEY (id),
    CONSTRAINT uk_payments_external_reference UNIQUE (external_reference),
    CONSTRAINT ck_payments_amount_positive CHECK (amount_rub > 0)
);

CREATE INDEX ix_payments_payer_username ON payments (payer_username);
CREATE INDEX ix_payments_payment_date ON payments (payment_date DESC, id DESC);
